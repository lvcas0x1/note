package content

import (
	"os"
	"path/filepath"
	"testing"
)

// TestChromaCSSFile keeps the web app's highlighting stylesheet in sync with
// the chroma style used at build time. Run with -update to rewrite it.
func TestChromaCSSFile(t *testing.T) {
	css, err := ChromaCSS()
	if err != nil {
		t.Fatal(err)
	}
	want := "/* Generated by server/internal/content (go test -run TestChromaCSSFile -update). Do not edit. */\n" + css
	file := filepath.Join("..", "..", "..", "apps", "web", "src", "styles", "chroma.css")
	if *update {
		if err := os.WriteFile(file, []byte(want), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(file)
	if err != nil {
		t.Fatalf("read %s (run with -update): %v", file, err)
	}
	if string(got) != want {
		t.Fatalf("%s is out of date; run go test ./internal/content -run TestChromaCSSFile -update", file)
	}
}
